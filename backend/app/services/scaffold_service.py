from __future__ import annotations

import json
import re
from pathlib import Path
from sqlalchemy.orm import Session

from app.config import get_settings
from app.models import IdeaModel
from app.schemas import ScaffoldRequest, ScaffoldResponse


def slugify(name: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")
    return slug[:60] or "hackathon-project"


def _write_text(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8", newline="\n")


def generate_scaffold(payload: ScaffoldRequest, db: Session) -> ScaffoldResponse:
    if payload.idea_id is not None:
        idea = db.query(IdeaModel).filter(IdeaModel.id == payload.idea_id).first()
        if not idea:
            raise LookupError(f"Idea {payload.idea_id} not found.")
        project_name = idea.title
        one_liner = idea.one_liner
        try:
            tech = json.loads(idea.tech_json) if idea.tech_json else []
        except json.JSONDecodeError:
            tech = []
    else:
        project_name = (payload.project_name or "").strip()
        one_liner = (payload.one_liner or "FastAPI + React hackathon starter generated by Hackathon Champ.").strip()
        tech = [t.strip() for t in payload.tech if t.strip()]

    slug = slugify(project_name)
    settings = get_settings()
    ws_root = settings.workspace_out_dir.resolve()
    ws_root.mkdir(parents=True, exist_ok=True)

    target_dir = (ws_root / slug).resolve()
    if not target_dir.is_relative_to(ws_root) or target_dir == ws_root:
        raise ValueError("Invalid project slug path.")

    tech_list_md = "\n".join(f"- {item}" for item in (tech or ["FastAPI", "React", "Vite", "TypeScript"]))
    safe_title_py = json.dumps(project_name)
    safe_oneliner_py = json.dumps(one_liner)
    safe_tech_py = json.dumps(tech or ["FastAPI", "React", "Vite"])

    files_map: dict[str, str] = {
        "README.md": f"""# {project_name}

> {one_liner}

Generated deterministically by **Hackathon Champ** (no AI required).

## Tech Stack
{tech_list_md}

## Quick Start

### 1. Run the Backend (FastAPI)
```bash
cd backend
python -m venv .venv
# Windows: .venv\\Scripts\\activate | macOS/Linux: source .venv/bin/activate
pip install -r requirements.txt
uvicorn main:app --reload --port 8001
```
Verify health check: `http://localhost:8001/health`

### 2. Run the Frontend (React + Vite)
```bash
cd frontend
npm install
npm run dev
```
Open `http://localhost:5174` in your browser.
""",
        "backend/requirements.txt": """fastapi==0.165.0
uvicorn==0.54.0
pydantic==2.14.4
""",
        "backend/main.py": f"""from fastapi import FastAPI
from fastapi.middleware.cors import CORSMiddleware

PROJECT_TITLE = {safe_title_py}
PROJECT_ONE_LINER = {safe_oneliner_py}
PROJECT_TECH = {safe_tech_py}

app = FastAPI(title=PROJECT_TITLE, version="0.1.0")

app.add_middleware(
    CORSMiddleware,
    allow_origins=["http://localhost:5174", "http://localhost:5173"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)


@app.get("/health")
def health() -> dict:
    return {{"status": "ok", "project": PROJECT_TITLE}}


@app.get("/api/info")
def info() -> dict:
    return {{
        "title": PROJECT_TITLE,
        "one_liner": PROJECT_ONE_LINER,
        "tech": PROJECT_TECH,
    }}
""",
        "frontend/package.json": json.dumps(
            {
                "name": slug,
                "private": True,
                "version": "0.1.0",
                "type": "module",
                "scripts": {
                    "dev": "vite --port 5174",
                    "build": "tsc -b && vite build",
                },
                "dependencies": {
                    "react": "19.3.1",
                    "react-dom": "19.3.1",
                },
                "devDependencies": {
                    "@types/react": "19.3.0",
                    "@types/react-dom": "19.3.0",
                    "@vitejs/plugin-react": "6.3.0",
                    "typescript": "7.0.2",
                    "vite": "8.3.8",
                },
            },
            indent=2,
        )
        + "\n",
        "frontend/tsconfig.json": """{
  "compilerOptions": {
    "target": "ES2022",
    "lib": ["ES2022", "DOM", "DOM.Iterable"],
    "module": "ESNext",
    "moduleResolution": "bundler",
    "jsx": "react-jsx",
    "strict": true,
    "noEmit": true
  },
  "include": ["src"]
}
""",
        "frontend/vite.config.ts": """import { defineConfig } from "vite";
import react from "@vitejs/plugin-react";

export default defineConfig({
  plugins: [react()],
  server: { port: 5174 },
});
""",
        "frontend/index.html": f"""<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <title>{project_name}</title>
  </head>
  <body style="margin:0;background:#0b101b;color:#eef4fc;font-family:system-ui,sans-serif;">
    <div id="root"></div>
    <script type="module" src="/src/main.tsx"></script>
  </body>
</html>
""",
        "frontend/src/main.tsx": """import { StrictMode } from "react";
import { createRoot } from "react-dom/client";
import App from "./App";

createRoot(document.getElementById("root")!).render(
  <StrictMode>
    <App />
  </StrictMode>
);
""",
        "frontend/src/App.tsx": f"""import {{ useEffect, useState }} from "react";

export default function App() {{
  const [status, setStatus] = useState<string>("checking...");

  useEffect(() => {{
    fetch("http://localhost:8001/health")
      .then((r) => r.json())
      .then((d) => setStatus(d.status === "ok" ? "Backend Online" : "Unexpected response"))
      .catch(() => setStatus("Start backend on port 8001 to connect"));
  }}, []);

  return (
    <main style={{{{ maxWidth: 760, margin: "4rem auto", padding: "0 1.5rem" }}}}>
      <h1 style={{{{ fontSize: "2.25rem", marginBottom: "0.5rem" }}}}>{project_name}</h1>
      <p style={{{{ color: "#9eb0cc", fontSize: "1.1rem" }}}}>{one_liner}</p>
      <div style={{{{ marginTop: "1.5rem", padding: "1rem", border: "1px solid #263452", borderRadius: 12, background: "#121a2b" }}}}>
        <strong>API Status:</strong> {{status}}
      </div>
    </main>
  );
}}
""",
    }

    written_files: list[str] = []
    for rel_path, content in files_map.items():
        full_path = (target_dir / rel_path).resolve()
        if not full_path.is_relative_to(target_dir):
            raise ValueError("Unsafe template path.")
        _write_text(full_path, content)
        written_files.append(rel_path)

    return ScaffoldResponse(
        path=str(target_dir),
        slug=slug,
        files=written_files,
    )
